# Weighted t-test for multiple samples
# Uses the sample matrix generated by SampleMatrix()
WT.MultiSample <- function(sample.matrix,features=NULL,t.test=FALSE ,min.pct=0.03,fc.thr=1,max.pval=1,df.correction=FALSE,sum.w2=0.4,min.cells=10,min.count=10) {
  AV1<-sample.matrix[[1]]                                                            # read average expression matrix
  var1<-sample.matrix[[2]]                                                           # read variance matrix
  AV2<-sample.matrix[[3]]
  var2<-sample.matrix[[4]]
  pct1<-sample.matrix[[5]]                                                           # read expression fraction matrix
  pct2<-sample.matrix[[6]]
  cnt1<-sample.matrix[[7]]
  cnt2<-sample.matrix[[8]]
  Ncd1<-sample.matrix[[9]]
  Ncd2<-sample.matrix[[10]]
  Agc1<-sample.matrix[[11]]
  Agc2<-sample.matrix[[12]]
  Sstats<-sample.matrix[["Sstats"]]
  fr <- .resolve_features(features, rownames(AV1))
  GeneList <- fr$genes                                                                # check for genes to be analyzed
  OrphanGenes <- fr$orphan
  .validate_common_params(fc.thr = fc.thr, min.pct = min.pct, max.pval = max.pval,
                          min.count = min.count, sum.w2 = sum.w2, min.cells = min.cells)
  data1<-as.matrix(AV1)                                                              # setting up data matrices
  data2<-as.matrix(AV2)                                                              
  N1=ncol(data1)                                                                     # number of samples in group 1 included in the analysis
  N2=ncol(data2)                                                                     # number of samples in group 2 included in the analysis
  wi.1eq=rep(1/N1, N1)                                                               # equal weights for samples in group 1
  wi.2eq=rep(1/N2, N2)                                                               # equal weights for samples in group 2
  nmax <- length(GeneList)
  output <- data.frame(log2FC=rep(NA_real_, nmax), p.value=rep(NA_real_, nmax),
                       `Wtd.%UMI.1`=rep(NA_real_, nmax), `Sd.%UMI.1`=rep(NA_real_, nmax), `Av.cell.fr.1`=rep(NA_real_, nmax),
                       `N.+_cells.1`=rep("", nmax), `Counts.1`=rep("", nmax), `Counts/cell.1`=rep(NA_real_, nmax), `Sum_w^2.1`=rep(NA_real_, nmax),
                       `Wtd.%UMI.2`=rep(NA_real_, nmax), `Sd.%UMI.2`=rep(NA_real_, nmax), `Av.cell.fr.2`=rep(NA_real_, nmax),
                       `N.+_cells.2`=rep("", nmax), `Counts.2`=rep("", nmax), `Counts/cell.2`=rep(NA_real_, nmax), `Sum_w^2.2`=rep(NA_real_, nmax),
                       check.names = FALSE, stringsAsFactors = FALSE)
  rowi<-0                                                                            # output row counter
  print("Performing weighted t-test:")
  pb <- txtProgressBar(min = 0, max = length(GeneList), initial = 0, style = 3)      # initialize progress bar
  for (rownum in seq_along(GeneList)) {                                              # gene by gene DGE calculation loop
    gene <- GeneList[[rownum]]
    Xi1<-data1[gene,]                                                                 # data vectors for groups 1 and 2  
    Xi2<-data2[gene,]
    VARi1<-var1[gene,]                                                                # variance vectors for groups 1 and 2
    VARi2<-var2[gene,]
    PCTi1<-pct1[gene,]                                                                # expression fraction vectors for groups 1 and 2 
    PCTi2<-pct2[gene,]
    CNTi1<-cnt1[gene,]                                                                # count/cell vectors for groups 1 and 2 
    CNTi2<-cnt2[gene,]
    NCDi1<-Ncd1[gene,]                                                                # number of positive cells vectors
    NCDi2<-Ncd2[gene,]
    AGCi1<-Agc1[gene,]                                                                # aggregate count vectors
    AGCi2<-Agc2[gene,]
    Ns1=sum(NCDi1>=min.cells)                                                        # number of samples containing >min.cells
    Ns2=sum(NCDi2>=min.cells)
    CellStat1=paste(NCDi1,collapse = ":")                                            # number of positive cell vector output
    CellStat2=paste(NCDi2,collapse = ":")
    CountStat1=paste(AGCi1,collapse = ":")                                           # aggregate count vector output
    CountStat2=paste(AGCi2,collapse = ":")
# selecting genes meeting minimum sample and expression requirements    
    if (N1 >= 3 && N2 >= 3 && (mean(PCTi1)>=min.pct || mean(PCTi2)>=min.pct) && (Ns1>=3 || Ns2>=3) && (sum(AGCi1)>=min.count || sum(AGCi2)>=min.count)){
# selection criteria: (a) Number of samples in each group >= 3 (N1 >= 3 && N2 >= 3)
#                     (b) Fraction of cells expressing the gene in 1 of 2 groups >= min.pct (mean(PCTi1)>=min.pct || mean(PCTi2)>=min.pct)
#                     (c) Number of samples with enough cells (>=min.cells) expressing the gene >= 3 in one of 2 groups (Ns1>=3 || Ns2>=3)
#                     (d) Aggregate count in one of two sample groups >= min.count (sum(AGCi1)>=min.count || sum(AGCi2)>=min.count)
      wi.1<-if(t.test==TRUE || Ns1<3) {wi.1eq} else {IterVar(Xi1,VARi1)}             # calculating weights for groups 1 and 2
      wi.2<-if(t.test==TRUE || Ns2<3) {wi.2eq} else {IterVar(Xi2,VARi2)} 
      wi.1sq<-sum(wi.1^2)                                                            # sum of w^2
      wi.2sq<-sum(wi.2^2)
      wi.1<-if(wi.1sq>sum.w2) {wi.1eq} else(wi.1)                                    # switching to equal weights when sum(w^2)>sum.w2 or Ns<3 
      wi.2<-if(wi.2sq>sum.w2) {wi.2eq} else(wi.2)                                    #(conservative average and variance calculation)
      Xi1av<-sum(Xi1*wi.1)                                                           # weighted average expression for groups 1 and 2
      Xi2av<-sum(Xi2*wi.2)
      Xi1sd<-sqrt(sum(wi.1^2*(Xi1-Xi1av)^2)/(1-sum(wi.1^2)))                         # standard deviations for the weighted averages
      Xi2sd<-sqrt(sum(wi.2^2*(Xi2-Xi2av)^2)/(1-sum(wi.2^2)))
      fc <- Xi1av/Xi2av                                                              # fold change (FC)
      if (!is.na(fc)){                                                                # removing 0/0 division
        if (fc >= fc.thr || fc <= 1/fc.thr) {                                        # checking FC threshold
          if(df.correction) {wTtest <- as.numeric(alt.wttest2(Xi1,Xi2,wi.1,wi.2))}   # weighted t-test with effective df
          else {wTtest <- as.numeric(alt.wttest(Xi1,Xi2,wi.1,wi.2))}                 # weighted t-test without df correction
          if(is.na(wTtest) || wTtest <= max.pval) {                                   # keep exact prior behavior: include NA p-values or <= max.pval
            rowi<-rowi+1
            output[rowi, ] <- list(log(fc,2), wTtest, Xi1av, Xi1sd, mean(PCTi1), CellStat1, CountStat1, mean(CNTi1), mean(wi.1sq),
                                    Xi2av, Xi2sd, mean(PCTi2), CellStat2, CountStat2, mean(CNTi2), mean(wi.2sq))
            row.names(output)[rowi]<-gene
          }
        } 
      }
    }
    setTxtProgressBar(pb, rownum)                                                     # progress bar update
  }
  close(pb)                                                                           # close progress bar
  output <- .trim_output(output, rowi)
  .warn_orphans(OrphanGenes)
  param<-as.character(c(t.test,min.pct,fc.thr,max.pval,min.cells,min.count,sum.w2,df.correction))
  names(param)<-c("t.test","min.pct","fc.thr","max.pval","min.cells","min.count","sum.w2","df.correction")
  list(DGE=output,Sstats=Sstats,parameters=param)
}
