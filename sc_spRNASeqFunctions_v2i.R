DGE.2samples <- function(object,features=NULL,ident.1=NULL,ident.2=NULL,
                         fc.thr=1,min.pct=0,max.pval=1,min.count=30,
                         icc="i",df.correction=FALSE,sum.w2=0.4,min.cells=10) {
  .validate_common_params(fc.thr = fc.thr, min.pct = min.pct, max.pval = max.pval,
                          min.count = min.count, sum.w2 = sum.w2, min.cells = min.cells)
  IWT<-IterWghtTtest(object,features,ident.1,ident.2,fc.thr,min.pct,max.pval=max.pval,min.count,icc=icc,df.correction,sum.w2,min.cells)
  Chi2<-Chi2Test(object,features=rownames(IWT),ident.1,ident.2,fc.thr=1,min.pct,max.pval=1,min.count)
  features<-intersect(rownames(Chi2),rownames(IWT))
  output<-IWT[features,]
  output[features,"Chi2.p.value"]<-Chi2[features,2]
  return(output)
}
#Chi2 test
Chi2Test <- function(object,features=NULL,ident.1=NULL,ident.2=NULL,fc.thr=1,min.pct=0,max.pval=1,min.count=30) {
  fr <- .resolve_features(features, rownames(object))
  GL <- fr$genes
  OrphanGenes <- fr$orphan
  .validate_common_params(fc.thr = fc.thr, min.pct = min.pct, max.pval = max.pval,
                          min.count = min.count, sum.w2 = 0.4, min.cells = 0)
  if (is.null(ident.1) || is.null(ident.2)) {stop("Two identities in a Seurat object must be defined using ident.1= and ident.2=")}
  nmax <- length(GL)
  output <- data.frame(log2FC=rep(NA_real_, nmax), p.value=rep(NA_real_, nmax),
                       `Counts/Cell.1`=rep(NA_real_, nmax), `Counts/Cell.2`=rep(NA_real_, nmax),
                       check.names = FALSE)                                                                            # preallocated output dataframe
  rowi <- 0
  if(length(GL)>0){
    object.1 <- subset(object, idents = ident.1)                                                                       # object subsetting
    object.2 <- subset(object, idents = ident.2)
    Ci.1 <- object.1[["RNA"]]$counts                                                                                   # count matrices
    Ci.2 <- object.2[["RNA"]]$counts
    Nc.1 <- ncol(Ci.1)                                                                                                 # number of cells
    Nc.2 <- ncol(Ci.2)
    AC.1 <- Matrix::rowSums(Ci.1)                                                                                      # aggregate counts /gene
    AC.2 <- Matrix::rowSums(Ci.2)
    NCD.1 <- Matrix::rowSums(Ci.1 != 0)                                                                                # positive cell counts /gene
    NCD.2 <- Matrix::rowSums(Ci.2 != 0)
    TC.1 <- sum(AC.1)                                                                                                  # total counts /sample
    TC.2 <- sum(AC.2)
    print("Performing chi^2 test:")
    pb <- txtProgressBar(min = 0, max = length(GL), initial = 0, style = 3)                                            # initialize progress bar
    for (rownum in seq_along(GL)) {                                                                                     # main loop, gene by gene
      gene <- GL[[rownum]]
      if ((AC.1[gene] >= min.count || AC.2[gene] >= min.count) &&                                                      # checking for min.count and min.pct
          ((NCD.1[gene]/Nc.1>min.pct) || (NCD.2[gene]/Nc.2>min.pct))){
        ContTable <- matrix(c(TC.1 - AC.1[gene], TC.2 - AC.2[gene],                                                    # contingency table for chi2 test
                              AC.1[gene], AC.2[gene]), nrow = 2, ncol = 2)
        fc <- as.numeric((AC.1[gene]/TC.1)/(AC.2[gene]/TC.2))                                                           # fold change (FC)
        if(!is.na(fc)){                                                                                                # removing features with undefined FC (=0/0)
          if (fc >= fc.thr || fc <= 1/fc.thr) {                                                                        # checking FC threshold
            chisquare <- as.numeric(chisq.test(ContTable)$p.value)                                                     # chi2 test
            if (chisquare <= max.pval) {                                                                               # checking max.pval threshold
              rowi<-rowi+1
              output[rowi, ] <- c(log(fc,2), chisquare, AC.1[gene]/Nc.1, AC.2[gene]/Nc.2)                            # output assembly
              row.names(output)[rowi]<-gene
            }  
          }
        }
      }
      setTxtProgressBar(pb, rownum)                                                                                    # progress bar update
    }
    close(pb)                                                                                                          # close progress bar                           
  }
  output <- .trim_output(output, rowi)
  .warn_orphans(OrphanGenes)
  return(output)
}
#Weighted t-test with iterative weight calculation
IterWghtTtest <- function(object,features=NULL,ident.1=NULL,ident.2=NULL,fc.thr=1,min.pct=0,max.pval=1,min.count=30,
                          icc="i",df.correction=FALSE,sum.w2=0.4,min.cells=10) {
  fr <- .resolve_features(features, rownames(object))
  GeneList <- fr$genes
  OrphanGenes <- fr$orphan
  .validate_common_params(fc.thr = fc.thr, min.pct = min.pct, max.pval = max.pval,
                          min.count = min.count, sum.w2 = sum.w2, min.cells = min.cells)
  if (is.null(ident.1) || is.null(ident.2)) {stop("Two identities in a Seurat object must be defined using ident.1= and ident.2=")}
  nmax <- length(GeneList)
  output <- data.frame(log2FC=rep(NA_real_, nmax), p.value=rep(NA_real_, nmax),                          # preallocated output dataframe
                       `Counts/Cell.1`=rep(NA_real_, nmax), `Counts/Cell.2`=rep(NA_real_, nmax),
                       `N.+_cells.1`=rep(NA_real_, nmax), `N.+_cells.2`=rep(NA_real_, nmax),
                       `Counts.1`=rep(NA_real_, nmax), `Counts.2`=rep(NA_real_, nmax),
                       `Sum_w^2.1`=rep(NA_real_, nmax), `Sum_w^2.2`=rep(NA_real_, nmax),
                       check.names = FALSE)
  object.1 <- subset(object, idents = ident.1)                                                           # ident.1 object
  Ci.1 <- object.1[["RNA"]]$counts                                                                        # ident.1 count matrix (sparse)
  Ni.1 <- Matrix::colSums(Ci.1)                                                                          # ident.1 Ni vector
  Nc.1 <- ncol(Ci.1)                                                                                     # ident.1 number of cells
  object.2 <- subset(object, idents = ident.2)
  Ci.2 <- object.2[["RNA"]]$counts
  Ni.2 <- Matrix::colSums(Ci.2)
  Nc.2 <- ncol(Ci.2)
  AC.1 <- Matrix::rowSums(Ci.1)
  AC.2 <- Matrix::rowSums(Ci.2)
  NCD.1 <- Matrix::rowSums(Ci.1 != 0)
  NCD.2 <- Matrix::rowSums(Ci.2 != 0)
  CandidateGenes <- GeneList[(AC.1[GeneList] >= min.count | AC.2[GeneList] >= min.count) &
                               (NCD.1[GeneList] >= min.cells | NCD.2[GeneList] >= min.cells) &
                               ((NCD.1[GeneList]/Nc.1 > min.pct) | (NCD.2[GeneList]/Nc.2 > min.pct))]
  if (length(CandidateGenes) > 0L) {
    if (!requireNamespace("MatrixExtra", quietly = TRUE)) {
      stop("Package 'MatrixExtra' is required for CSR row-wise access in this version.")
    }
    Ri.1 <- MatrixExtra::as.csr.matrix(Ci.1)
    Ri.2 <- MatrixExtra::as.csr.matrix(Ci.2)
    gene_idx_1 <- match(CandidateGenes, rownames(Ri.1))
    gene_idx_2 <- match(CandidateGenes, rownames(Ri.2))
  }
  rowi<-0
  print("Performing weighted t-test:")
  pb <- txtProgressBar(min = 0, max = max(1L, length(CandidateGenes)), initial = 0, style = 3)          # initialize progress bar# output row counter
  processed <- 0L
  if (length(CandidateGenes) > 0) {
    for (i in seq_along(CandidateGenes)) {                                                                  # Main test loop with sparse CSR row access
      gene <- CandidateGenes[[i]]
      AC1 <- AC.1[gene]                                                                                     # ident.1 aggregated counts
      AC2 <- AC.2[gene]                                                                                     # ident.2 aggregated counts
      Ncd.1 <- NCD.1[gene]                                                                                  # number of cells expressing the gene
      Ncd.2 <- NCD.2[gene]
      h1 <- as.numeric(Ri.1[gene_idx_1[[i]], , drop = FALSE])
      h2 <- as.numeric(Ri.2[gene_idx_2[[i]], , drop = FALSE])
      Xi1 <- h1/Ni.1                                                                                        # ident.1 normalized counts
      Xi2 <- h2/Ni.2                                                                                        # ident.2 normalized counts
      wi.1 <- ICCWeight(h = h1, n = Ni.1, icc = icc)                                                       # ident.1 weights
      wi.2 <- ICCWeight(h = h2, n = Ni.2, icc = icc)                                                       # ident.2 weights
      wi.1sq <- sum(wi.1^2)                                                                                # sum of w^2
      wi.2sq <- sum(wi.2^2)
      wi.1 <- if(wi.1sq>sum.w2) {rep(1/Nc.1, Nc.1)} else {wi.1}                                            # switching to equal weights when sum(w^2)>sum.w2 (conservative average and variance calculation when 1 cell appears to dominate)
      wi.2 <- if(wi.2sq>sum.w2) {rep(1/Nc.2, Nc.2)} else {wi.2}
      fc <- sum(Xi1*wi.1)/sum(Xi2*wi.2)                                                                    # fold change
      if (!is.na(fc)){                                                                                      # removing 0/0 division
        if ((fc >= fc.thr || fc <= 1/fc.thr)) {                                                            # checking FC threshold
          if(df.correction==TRUE) {wTtest <- as.numeric(alt.wttest2(Xi1,Xi2,wi.1,wi.2))}                  # weighted t-test with effective df
          else {wTtest <- as.numeric(alt.wttest(Xi1,Xi2,wi.1,wi.2))}                                       # weighted t-test without df correction
          if (wTtest <= max.pval) {                                                                         # checking p-value threshold
            rowi<-rowi+1                                                                                    # output row counter
            output[rowi, ] <- c(log(fc,2), wTtest, AC1/Nc.1, AC2/Nc.2, Ncd.1, Ncd.2, AC1, AC2, wi.1sq, wi.2sq) # output
            row.names(output)[rowi]<-gene
          }
        }
      }
      processed <- processed + 1L
      setTxtProgressBar(pb, processed)                                                                      # progress bar update
    }
  }
  close(pb)                                                                                              # close progress bar
  output <- .trim_output(output, rowi)
  .warn_orphans(OrphanGenes)
  return(output)
}
alt.wttest <- function(x1, x2, w1, w2) {
  # alternative weighted t-test based on Margolin-Leikin variance estimator
  stopifnot(length(x1)==length(w1) && length(x2)==length(w2))
  w1 = w1/sum(w1)
  m1 = sum(x1*w1)
  vm1 = sum(w1^2*(x1-m1)^2) / (1-sum(w1^2)) # unbiased when w ~ 1/s^2 (and sum(w)=1)
  w2 = w2/sum(w2)
  m2 = sum(x2*w2)
  vm2 = sum(w2^2*(x2-m2)^2) / (1-sum(w2^2)) # unbiased when w ~ 1/s^2 (and sum(w)=1)
  s12 = sqrt(vm1 + vm2)
  t = (m1 - m2) / s12
  df = s12^4 / (vm1^2/(length(x1)-1) + vm2^2/(length(x2)-1)) 
  p = 2*pt(-abs(t), df=df)
  return(p)
}
alt.wttest2 <- function(x1, x2, w1, w2) {
  # alternative weighted t-test based on Margolin-Leikin variance estimator and effective degrees of freedom
  stopifnot(length(x1)==length(w1) && length(x2)==length(w2))
  w1 = w1/sum(w1)
  n1 = 1/sum(w1^2)
  m1 = sum(x1*w1)
  vm1 = sum(w1^2*(x1-m1)^2) / (1-1/n1) # unbiased when w ~ 1/s^2 (and sum(w)=1)
  w2 = w2/sum(w2)
  n2 = 1/sum(w2^2)
  m2 = sum(x2*w2)
  vm2 = sum(w2^2*(x2-m2)^2) / (1-1/n2) # unbiased when w ~ 1/s^2 (and sum(w)=1)
  s12 = sqrt(vm1 + vm2)
  t = (m1 - m2) / s12
  df = s12^4 / (vm1^2/(n1-1) + vm2^2/(n2-1)) 
  p = 2*pt(-abs(t), df=df)
  return(p)
}
#Calculation of weights based on ICC
ICC.AN<-function(h,n){
  N=sum(n)                                                    #ANOVA ICC calculation
  k=length(n)
  n0=(1/(k-1))*(N-sum(n^2/N))
  MSw=(1/(N-k))*(sum(h)-sum(h^2/n))
  MSb=(1/(k-1))*(sum(h^2/n)-(1/N)*(sum(h))^2)
  if ((MSb+(n0-1)*MSw)==0) {ICC=0}                            #setting ICC=0 when ANOVA denominator = 0
  else ICC=(MSb-MSw)/(MSb+(n0-1)*MSw)
  if(ICC < 0) ICC=0                                           #resetting negative ICC to 0
  if(ICC > 1) ICC=1                                           #resetting ICC>1 to ICC=1
  return(ICC)
}
ICC.iter<-function(h,n){                                      #Iterative ICC calculation
  x=h/n
  w0<-n/sum(n)                                              # initial weights 
  x0<-sum(x*w0)                                             # initial weighted average count
  VarT0<-x0*(1-x0)/sum(n)                                   # initial variance @ icc=0
  VarE0<-sum(w0^2*(x-x0)^2)/(1-sum(w0^2))                   # initial measured variance with w0 weights
  if (VarE0<=VarT0){icc=0}    
  else{
    f <- function(icc,h=h,n=n) {
      x = h/n                                                   #normalized counts
      wprop = n/(1 + icc*(n-1))                                 #proportional weights
      w <- wprop/sum(wprop)                                     #normalized weights
      x1 = sum(x*w)                                             #weighted average
      VarT<-x1*(1-x1)/(sum(wprop))                              #VarT 
      VarE<-sum(w^2*(x-x1)^2)/(1-sum(w^2))                      #VarE
      VarE-VarT                                                 #VarE-VarT
    }
    ur = uniroot(f, 0:1, n=n, h=h, check.conv=T, extendInt="downX", tol = 1e-4/max(n))
    icc = ur$root
    if(icc > 1) icc=1                                           #resetting ICC>1 to ICC=1
  }
  return(icc)
}
ICCWeight <- function(h,n,icc="i") {                     #Calculation of weights based on ICC
  Nc<-length(n)
  if(length(h)!=Nc) {stop("Unequal lengths of Ni and Nzi vectors")} 
  if(Nc<3) {stop("At least 3 cells are required in each ident")}
  if (sum(h!=0)<3){w<-rep(1/Nc,Nc)} #exit and return equal weights if the number cells/samples with nonzero counts is less than 3
  else {
    if(icc=="i"){icc=ICC.iter(h,n)} else {
      if(icc=="A"){icc=ICC.AN(h,n)} else {
        if (icc==0) {icc=0} else {
          if (icc==1) {icc=1} else {
            stop("Invalid icc, must be icc = 'i', 'A', 0, or 1")
          }
        }  
      }
    } 
    wprop = n/(1 + icc*(n-1))                                 #proportional weights
    w <- wprop/sum(wprop)
  }
  return(w)
}
