# Internal helpers to keep validation and output handling consistent.
.resolve_features <- function(features, universe) {
  if (is.null(features)) {
    return(list(genes = universe, orphan = character(0)))
  }
  requested <- as.vector(features)
  list(genes = intersect(requested, universe), orphan = setdiff(requested, universe))
}

.warn_orphans <- function(orphan) {
  if (length(orphan) > 0) {
    warning(paste0(toString(orphan), " gene(s) were not found in the object."))
  }
}

.trim_output <- function(output, n_used) {
  if (n_used > 0) {
    output[seq_len(n_used), , drop = FALSE]
  } else {
    output[0, , drop = FALSE]
  }
}

.validate_common_params <- function(fc.thr, min.pct, max.pval, min.count, sum.w2, min.cells) {
  if (!is.numeric(fc.thr) || length(fc.thr) != 1 || is.na(fc.thr) || fc.thr <= 0) {
    stop("fc.thr must be a single positive numeric value")
  }
  if (!is.numeric(min.pct) || length(min.pct) != 1 || is.na(min.pct) || min.pct < 0 || min.pct > 1) {
    stop("min.pct must be a single numeric value in [0,1]")
  }
  if (!is.numeric(max.pval) || length(max.pval) != 1 || is.na(max.pval) || max.pval < 0 || max.pval > 1) {
    stop("max.pval must be a single numeric value in [0,1]")
  }
  if (!is.numeric(min.count) || length(min.count) != 1 || is.na(min.count) || min.count < 0) {
    stop("min.count must be a single non-negative numeric value")
  }
  if (!is.numeric(sum.w2) || length(sum.w2) != 1 || is.na(sum.w2) || sum.w2 <= 0 || sum.w2 > 1) {
    stop("sum.w2 must be a single numeric value in [0,1]")
  }
  if (!is.numeric(min.cells) || length(min.cells) != 1 || is.na(min.cells) || min.cells < 0) {
    stop("min.cells must be a single non-negative numeric value")
  }
}

#####################################################
# DESCRIPTION OF KEY FUNCTIONS
#####################################################
# 1.	DGE.2samples() analyzes DGE between 2 identities or 2 groups of identities in a Seurat object based on weighted-t-test and chi-squared-test.
# 2.	IterWghtTest() same as DGE.2samples but performs only the weighted t-test (called by DGE.2Samples).
# 3.	DGE.Multisample() performs analysis of DGE between 2 groups of samples (at least 3 samples in each group)
#
# Both DGE.2samples() and DGE.Multisample() can be used for scRNASeq and spRNASeq.
# However, different parameters are recommended for different assays (see below).
# In the output from all functions, log2FC is base 2 logarithm of weighted-average.1/weighted-average.2,
# where 1 and 2 mark identities or samples 1 and 2, respectively.
############
#'*DGE.2samples(object,features=NULL,ident.1=NULL,ident.2=NULL,fc.thr=1,min.pct=0,max.pval=1,min.count=30,icc="i",df.correction=FALSE,sum.w2=0.4,min.cells=10)*
# object - Seurat's object for the analysis
# features - list of genes to be analyzed (e.g., features=c("Actb","Actg1",...)), features=NULL causes analysis of all genes (default)
# ident.1 and ident.2 - identities for 2 groups of cells to be analyzed, both must be defined; to combine multiple groups of cells 
#          within ident.1 and/or ident.2 use identity lists, e.g., ident.1 = c("WT1","WT2","WT3")
# fc.thr - fold-change threshold, e.g., fc.thr = 1 results reported for all genes, fc.thr = 2 results reported for genes 
#          that are up- or down-regulated more than 2-fold
# min.pct - minimum fraction of cells expressing the gene in at least one of the 2 groups, e.g., min.pct = 0 results reported for 
#           all genes, min.pct = 0.03 results reported for genes expressed at least by 3% of cells in one of the 2 groups
# max.pval - only genes with p-values less than max.pval are reported
# min.count - similar to min.pct but selects genes for analysis based on the minimum aggregate count, which should exceed min.count
#             in at least in one of the two group; min.count >= 30 is recommended.
# icc - intracluster correlation coefficient (ICC) to be used, allowed values: icc = "i", icc = "A", icc = 0, icc = 1
#       icc = "i" performs weighted t-test with iterative ICC (default)
#       icc = "A" performs weighted t-test with ANOVA ICC (slightly faster but may be less accurate)
#       icc = 0 uses weights based only on total RNA counts per cell (recommended for some spRNASeq assays, see paper)
#       icc = 1 assumes equal weights of all cells and performs common, unweighted t-test
# df.correction - correction for degrees of freedom due to uneven statistical weights; df.correction = TRUE performs a more stringent
#                 weighted t-test when the number of cells is < 30-50 (not recommended)
# sum.w2 - maximum value for the sum of squares of cell weights (default sum.w2=0.4), At sum(w^2)>sum.w2 all cell weights are set to be equal
#          to avoid dominance of just 1 or 2 cells in the weighted average. For more conservative results, use sum.w2=0.1.
# min.cells - minimum number of cells expressing a gene required in one of the two identities for the gene to be analyzed (default min.cells=10) 
#
#'* FUNCTION OUTPUT: dataframe with DGE analysis results*
#'* Output columns:*
# 1. log2FC - log base 2 of fold-change (FC, ident.1/ident2)
# 2. p.value - unadjusted p-value for the fold-chage
# 3. Counts/Cell.1 - Average counts per cell, ident 1
# 4. Counts/Cell.2 - Average counts per cell, ident 2
# Quality control columns in the output:
# 5. N.+_cells.1 - Number of cells expressing the gene, ident 1 
# 6. N.+_cells.2 - Number of cells expressing the gene, ident 2
# 7. Aggregate gene counts, ident 1
# 8. Aggregate gene counts, ident 2
# 9. Sum_w^2.1 - Sum of the squares of stat. weights, ident 1 
# 10. Sum_w^2.2 - Sum of the squares of stat. weights, ident 2 
# 11. Chi2.p.value - unadjusted p.value for aggregate counts in chi-squared test
#
#'* Quality control considerations:* 
# A. Small values of aggregate counts and N.+_cells in both identities precludes reliable statistical inference (not enough data points);
#    min.count parameter eliminates genes with aggregate counts <min.count in both identities, default min.count=30;
#    small aggregate count in just one of two identities does not affect the output accuracy;
#    min.cells parameter eliminates genes with N.+_cells<min.cells in both identities, default min.cells=10.
#    N.+_cells can be small or even zero in just one of the two identities without affecting the output accuracy.
# B. Accurate statistical weight calculation requires sum(w^2)<<1. When sum(w^2)>0.5, just one or two cell define the average. In these
#    cases, unequal statistical weights cannot be used for statistical inference. To avoid such situations, we use sum.w2 parameter.
#    When sum(w^2)>sum.w2 within an identity, all statistical weights within that identity are set to be equal, resulting in conservative
#    estimates for log2FC and p-values (decreasing the likelihood of false positive and increasing the likelihood of false negative findings).
#    The default setting is sum.w2=0.4. Smaller sum.w2 will produce more conservative results. Larger sum.w2 are not advisable.
#    There is no single recipe for optimal sum.w2 setting (use your judgement).
# C. Chi-squared test becomes inaccurate at low aggregate counts and may produce warnings. Borderline values of "Counts" in both samples may indicate reduced accuracy   
# D. Borderline values of N.+_cells and/or Sum_w^2 in both samples may also indicate reduced accuracy.
#    
#############
#'* IterWghtTest(object,features=NULL,ident.1=NULL,ident.2=NULL,fc.thr=1,min.pct=0,max.pval=1,min.count=30,icc="i",df.correction=FALSE,sum.w2=0.4,min.cells=10)*
#   All parameters are the same as in DGE.2samples()
#
# FUNCTION OUTPUT: dataframe with DGE analysis results
# All columns are the same as in DGE.2Samples(), no Chi2.p.value column
#############
#'* DGE.Multisample(object,samples.1=NULL,samples.2=NULL,features=NULL,t.test=FALSE, min.pct=0.03,fc.thr=1,max.pval=1,icc="i",df.correction=FALSE,sum.w2=0.4,min.cells=10,min.count=10)*
# samples.1 and samples.2 - lists of at least 3 identities of biological replicates in each of the 2 groups of samples, e.g.,
#                           samples.1 = c("WT1","WT2","WT3"), samples.2 = c("KO1","KO2","KO3")
#                           renaming multiple technical replicates into the same biological replicate identity is recommended, otherwise 
#                           technical replicates will be treated as biological ones
# t.test - t.test = FALSE performs weighted t-test with iterative ICC when comparing the samples, t.test = TRUE performs common, unweighted 
#                   t-test when comparing the samples
# min.pct, fc.thr, max.pval, df.correction (not recommended), sum.w2, and min.cells are the same parameters as in DGE.2samples()
# icc - same ICC selection as in DGE.2samples(); used for calculating the weighted average values within each sample but not for
#       comparing the two groups of samples
##
# FUNCTION OUTPUT: list of 3 items $DGE is a dataframe containing DGE analysis results, $Sstats is a dataframe containing sample statistics
#                  $parameters is a named list of calculation parameters
# Output columns in $DGE dataframe:
# 1. log2FC - log base 2 of fold-change (FC, samples.1/samples.2)
# 2. p.value - unadjusted p-value for the fold-chage
# 3. Wtd.%UMI.1 - weighted average expression in %UMI, samples.1
# 4. Sd.%UMI.1 - standard deviation of Wtd.%UMI.1 (commonly referred to as standard error of the mean, SEM)
# 5. Av.cell.fr.1 - average fraction of cells expressing the gene, samples.1 (Quality control)
# 6. N.+_cells.1 - number of cells expressing the gene in each sample of samples.1, e.g. N1:N2:N3:N4 means N1 cells in sample 1, N2 in sample 2, N3 in sample 3, and N4 in sample 4
# 7. Counts.1 - Aggregate counts of the gene in each sample of samples.1, same format as N.+_cells.1
# 8. Counts/cell.1 - average counts per cell, samples.1
# 9. Sum_w^2.1 - Sum of the squares of stat. weights of the samples, samples.1 (Quality control)
# 10-16. - same as 3-9 but for samples.2
#
#'* Quality control considerations: *
# A. Please see description of DGE.2Samples() for discussion of min.cells, min.count, and sum.w2 parameters.
#    The same default settings for min.cells and sum.w2 are used in the multi-sample analysis. The default setting of min.count here is 10 rather than 30 since the chi-squared test is not used. However,
#    we recommend caution in interpreting results with low aggregate counts in both groups of samples.
# B. In the context of multi-sample analysis, a gene is excluded from the analysis when the number of samples with enough cells (>=min.cells) expressing the gene drops below 3 in both groups of samples. 
# C. In the context of multi-sample analysis, Sum_w^2 is the sum of squares of statistical weights of samples rather than cells. Otherwise, the same considerations apply. Because the number of samples
#    per group is usually 3-to-5 (minimum 3 required, more than 5 rarely used due to high cost), we do not recommend overwriting the default sum.w2=0.4 setting. Smaller sum.w2 would make sense only for
#    a much larger number of samples while larger sum.w2 reduces accuracy of the results. Sum_w^2 > sum.w2 reported for a sample group means that equal weights were set for all samples in that group.
#    A weighted t-test is identical to a common t-test when the weights are equal within each of the two groups (Sum_w^2>sum.w2 reported for both groups).   
# D. In most cases, strange branches of volcano plots are caused by low expression genes. This can be confirmed by increasing the value of min.cells, which should remove such genes from the analysis.
#    When the number of cells per sample is relatively small to begin with and/or increasing min.cells (excluding insufficiently accurate analysis of low expression genes) is not a good solution for
#    your experiment, an alternative approach is to analyze aggregate rather than weighted average counts by using the setting icc=0 instead of default icc="i" and utilize more conservative common t-test
#    for the samples by setting t.test=TRUE instead of default t.test=FALSE. With these parameter settings, the value of min.cells can be reduced to min.cells=5 (may be even min.cells=3, although this is 
#    a stretch). There is no rigorous mathematical way to evaluate accuracy of such analysis. Trial and error may be the best approach, if you must analyze such data.
# E. Strange volcano plot branches may also indicate a problem in the experiments. For instance, cell-death genes in these branches may indicate presence of dying/dead cells in the selected cell groups.
#    Environment response genes may indicate strong nonlethal effects of cell isolation, causing biased cell selection for the analysis. "Random" genes may indicate RNA contamination. In our experience, 
#    this is always worth following up to ensure high quality of reported results. 
######################################################

