# Count averaging and variance calculation
# Usage: modified.object<-CntAv(object)
# Returns the original object with weighted average counts, their variances, and other sample stats added to object@misc 
CntAv<-function(object,features=NULL,icc="i"){
  fr <- .resolve_features(features, rownames(object))
  GeneList <- fr$genes                                                                   # check for genes to be analyzed
  OrphanGenes <- fr$orphan
  object@misc$AV.data<-list()                                                            # creating AV.data list in misc slot of the Seurat object 
  Samples<-levels(object@active.ident)                                                   # retrieving sample identities from the object
  Ns<-length(Samples)                                                                    # number of samples in the object
  Sstats<-matrix(nrow=3,ncol=Ns)
  colnames(Sstats)<-Samples
  rownames(Sstats)<-c("N.cells","N.counts","Counts/cell")
  Ng<-length(GeneList)
  if (Ng > 0L && !requireNamespace("MatrixExtra", quietly = TRUE)) {
    stop("Package 'MatrixExtra' is required for CSR row-wise access in this version.")
  }
  print("Averaging counts and calculating variance for each sample:")
  pb <- txtProgressBar(min = 0, max = Ns * Ng, initial = 0, style = 3)                   # initialize progress bar# number of genes    
  for (j in seq_len(Ns)){                                                                 # main loop for calculating weighted average and variance sample by sample
    sample=Samples[j]
    OBJ<-subset(object, idents=sample)                                                   # sample subsetting
    Ci<-OBJ[["RNA"]]$counts                                                               # count matrix
    Ni<-Matrix::colSums(Ci)                                                               # total counts vector (Ni)
    AC<-Matrix::rowSums(Ci)
    Nc<-ncol(Ci)                                                                         # number of cells
    Sstats["N.cells",j]<-Nc
    Sstats["N.counts",j]<-sum(Ni)
    Sstats["Counts/cell",j]<-Sstats["N.counts",j]/Sstats["N.cells",j]
    AV<-numeric(Ng)                                                                      # vector initialization
    VAR<-numeric(Ng)
    PCT<-numeric(Ng)
    CNT<-numeric(Ng)
    NCD<-numeric(Ng)
    AGC<-numeric(Ng)
    Ri <- if (Ng > 0L) MatrixExtra::as.csr.matrix(Ci) else NULL                          # one-time CSR conversion for fast row access
    gene_idx <- if (Ng > 0L) match(GeneList, rownames(Ri)) else integer(0)
    for (i in seq_len(Ng)){                                                               # gene by gene calculation subloop 
      h<-as.numeric(Ri[gene_idx[[i]], , drop = FALSE])                                   # vector of counts for gene i
      Nd<-sum(h!=0)                                                                      # number of cells expressing the gene
      w<-ICCWeight(h=h,n=Ni,icc=icc)                                                     # statistical weights
      x<-as.vector(100*h/Ni)                                                             # normalized genes counts
      AV[i]<-sum(x*w)                                                                    # weighted average gene count (% UMI)
      VAR[i]<-if(AV[i]!=0){sum(w^2*(x-AV[i])^2)/(1-sum(w^2))} else{1/(sum(Ni)^2)}        # variance of the weighted average or 1/sum(Ni)^2 when all x=0
      PCT[i]<-Nd/Nc                                                                      # fraction of cells expressing the gene
      CNT[i]<-mean(h)                                                                    # average counts per cell
      NCD[i]<-Nd
      AGC[i]<-as.numeric(AC[GeneList[i]])
      setTxtProgressBar(pb, (j - 1) * Ng + i)                                            # progress bar update
    }
    AVdat<-cbind(AV,VAR,PCT,CNT,NCD,AGC)                                                 # output matrix assembly
    rownames(AVdat)<-GeneList
    object@misc$AV.data[[sample]]<-as.data.frame(AVdat)                                  # writing output matrix into AV.data list within misc slot
  }
  close(pb)                                                                              # close progress bar
  object@misc$AV.data[["Sstats"]]<-as.data.frame(Sstats)
  .warn_orphans(OrphanGenes)
  return(object)
}
